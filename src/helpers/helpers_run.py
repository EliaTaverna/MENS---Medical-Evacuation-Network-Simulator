_DEFAULT_OUTPUTS = {
    "patient_log":       True,
    "safe_patients":     True,
    "transport_events":  True,
    "wait_times":        True,
    "facility_states":   False,  # expensive — only needed when make_video=True
}


def resolve_settings(scenario: dict, **overrides) -> dict:
    """Merge scenario defaults with caller overrides. Overrides win when not None."""
    sim_s = scenario.get("simulation", {})
    vid_s = scenario.get("video", {})
    log_s = scenario.get("logs", {})

    # Merge outputs: defaults <- scenario outputs section <- overrides
    out_s = scenario.get("outputs", {})
    outputs = {k: out_s.get(k, v) for k, v in _DEFAULT_OUTPUTS.items()}
    if overrides.get("outputs"):
        outputs.update(overrides["outputs"])

    def pick(override, default):
        return override if override is not None else default

    return {
        "levers": pick(overrides.get("levers"), scenario.get("levers", {
            "facility_eligibility": 0,
            "facility_assignment": 0,
            "ambulance_eligibility": 0,
            "ambulance_assignment": 0,
        })),
        "till":                 pick(overrides.get("till"),                 sim_s.get("till", 1000.0)),
        "trace":                pick(overrides.get("trace"),                sim_s.get("trace", False)),
        "casualty_seed":        pick(overrides.get("casualty_seed"),        sim_s.get("casualty_seed")),
        "make_video":           pick(overrides.get("make_video"),           vid_s.get("enabled", False)),
        "video_fps":            pick(overrides.get("video_fps"),            vid_s.get("fps", 24)),
        "video_time_scale":     pick(overrides.get("video_time_scale"),     vid_s.get("time_scale", 5.0)),
        "video_dpi":            pick(overrides.get("video_dpi"),            vid_s.get("dpi", 100)),
        "video_duration":       vid_s.get("duration"),
        "state_log_interval":   pick(overrides.get("state_log_interval"),   vid_s.get("state_log_interval", 5.0)),
        "save_logs":            pick(overrides.get("save_logs"),            log_s.get("enabled", True)),
        "outputs":              outputs,
    }


def create_run_folder(scenario: dict, scenario_path: str, output_folder: str) -> Path:
    """Create timestamped output folder and copy scenario file into it."""
    scenario_file = Path(scenario_path)
    scenario_name = scenario.get("name", scenario_file.stem)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    run_folder = Path(output_folder) / f"{timestamp}_{scenario_name}"
    run_folder.mkdir(parents=True, exist_ok=True)
    shutil.copy2(scenario_file, run_folder / scenario_file.name)
    print(f"Output folder: {run_folder}")
    return run_folder


def load_or_generate_casualties(scenario: dict, casualty_seed: int = None) -> pd.DataFrame:
    """Load pre-generated casualties from file, or generate them dynamically."""
    from src import load_casualties_from_scenario, load_casualty_config_from_scenario
    from src.helpers.casualty_generator import generate_casualties_df_from_waves

    cas_gen = scenario.get("casualty_generation", {})
    if cas_gen.get("from_dataset", False):
        casualties_df = load_casualties_from_scenario(scenario)
        print(f"Loaded {len(casualties_df)} casualties from dataset")
    else:
        config = load_casualty_config_from_scenario(scenario)
        if casualty_seed is not None:
            config["seed"] = casualty_seed
        full_df, _ = generate_casualties_df_from_waves(
            spawn_map=config["spawn_map"],
            par_total=config["par_total"],
            n_days=config["n_days"],
            waves_per_day=config["waves_per_day"],
            wave_duration_min=config["wave_duration_min"],
            diagnosis_mix_df=config["diagnosis_mix_df"],
            rx_df=config["rx_df"],
            lifetime_factory_by_triage=config["lifetime_factory_by_triage"],
            seed=config["seed"],
        )
        casualties_df = full_df[
            ~full_df["triage"].str.startswith(("KIA", "MIA"))
        ].copy().reset_index(drop=True)
        print(f"Generated {len(casualties_df)} casualties (excl. KIA/MIA from {len(full_df)} total)")
    return casualties_df


def prepare_run(
    scenario_path: str,
    output_folder: str = "data/single_run/output",
    **overrides,
) -> tuple:
    """Parse scenario, resolve settings, create output folder and load all data.

    Returns (data, settings, run_folder) ready to pass directly to run_simulation.
    """
    from src import load_scenario, load_data_from_scenario, load_triage_weights_from_scenario
    scenario = load_scenario(scenario_path)
    print(f"Loaded scenario: {scenario.get('name', Path(scenario_path).stem)}")
    s = resolve_settings(scenario, **overrides)
    run_folder = create_run_folder(scenario, scenario_path, output_folder)
    data = load_data_from_scenario(scenario)
    data["casualties_df"] = load_or_generate_casualties(scenario, s["casualty_seed"])
    data["triage_weights"] = load_triage_weights_from_scenario(scenario)
    return data, s, run_folder


def collect_results(env, observer, data: dict, settings: dict, run_folder: Path) -> dict:
    """Assemble the results dict from environment and observer data."""
    obs = observer.results()
    env.patient_log_df = pd.DataFrame(obs["patient_log_rows"], columns=obs["patient_log_columns"])

    transport_df = pd.DataFrame(env.transport_events)
    facility_states_df = pd.DataFrame(env.facility_states)
    wait_times_df = pd.DataFrame(env.wait_times) if env.wait_times else pd.DataFrame()
    safe_df = pd.DataFrame(
        [(p.patient_id, p.triage, p.t_safe, p.spawn_facility.loc_id) for p in env.safe],
        columns=["patient_id", "triage", "t_safe", "spawn_facility_id"],
    )

    print(f"Simulation complete. {len(env.safe)} patients safe.")
    print(f"Logged {len(transport_df)} transport events")
    print(f"Logged {len(facility_states_df)} facility state snapshots")

    return {
        "env": env,
        "safe_df": safe_df,
        "transport_df": transport_df,
        "facility_states_df": facility_states_df,
        "patient_log_df": env.patient_log_df,
        "wait_times_df": wait_times_df,
        "unit_busy_periods": env.unit_busy_periods,
        "all_patients": env.all_patients,
        "sim_duration": settings["till"],
        "run_folder": run_folder,
        "distance_matrix": data["distance_matrix"],
        "outputs": settings.get("outputs", _DEFAULT_OUTPUTS),
    }


def save_logs(results: dict) -> None:
    """Save simulation logs to xlsx files in the run folder.

    Which files are written is controlled by results["outputs"], which mirrors
    the scenario's ``outputs:`` section (defaults defined in _DEFAULT_OUTPUTS).
    """
    run_folder = results["run_folder"]
    outputs = results.get("outputs", _DEFAULT_OUTPUTS)
    saved = []

    if outputs.get("patient_log", True):
        results["patient_log_df"].to_excel(run_folder / "patient_log.xlsx", index=False)
        saved.append("patient_log.xlsx")
    if outputs.get("safe_patients", True):
        results["safe_df"].to_excel(run_folder / "safe_patients.xlsx", index=False)
        saved.append("safe_patients.xlsx")
    if outputs.get("transport_events", True):
        results["transport_df"].to_excel(run_folder / "transport_events.xlsx", index=False)
        saved.append("transport_events.xlsx")
    if outputs.get("wait_times", True) and not results["wait_times_df"].empty:
        results["wait_times_df"].to_excel(run_folder / "wait_times.xlsx", index=False)
        saved.append("wait_times.xlsx")
    if outputs.get("facility_states", False) and not results["facility_states_df"].empty:
        results["facility_states_df"].to_excel(run_folder / "facility_states.xlsx", index=False)
        saved.append("facility_states.xlsx")

    print(f"Logs saved to {run_folder}/: {', '.join(saved)}")


def make_video(data: dict, results: dict, settings: dict) -> None:
    """Generate MP4 animation from transport events."""
    transport_df = results["transport_df"]
    if transport_df.empty:
        return

    import matplotlib
    matplotlib.use("Agg")
    from src.helpers.visualization import create_transport_video

    video_path = results["run_folder"] / "simulation.mp4"
    print("\nCreating video...")
    create_transport_video(
        distance_matrix=data["distance_matrix"],
        facility_df=data["facility_df"],
        transport_events=transport_df,
        ambulance_df=data["ambulance_df"],
        facility_states_df=results["facility_states_df"],
        fps=settings["video_fps"],
        time_scale=settings["video_time_scale"],
        dpi=settings["video_dpi"],
        save_path=str(video_path),
        duration=settings["video_duration"],
    )


def print_summary(results: dict):
    """Print simulation summary statistics."""
    log_df = results["patient_log_df"]
    wait_times_df = results.get("wait_times_df", pd.DataFrame())
    transport_df = results.get("transport_df", pd.DataFrame())
    unit_busy_periods = results.get("unit_busy_periods", {})
    sim_duration = results.get("sim_duration", 0)
    distance_matrix = results.get("distance_matrix")

    print("\n" + "=" * 70)
    print("SIMULATION RESULTS")
    print("=" * 70)

    # -----------------------------------------------------------------
    # 1. Patient outcomes by triage
    # -----------------------------------------------------------------
    env = results.get("env")

    triage_map = {}
    if env and hasattr(env, "all_patients"):
        for pid, patient in env.all_patients.items():
            triage_map[pid] = patient.triage

    final_states = log_df.groupby("patient_id").last().reset_index()
    final_states["triage"] = final_states["patient_id"].map(triage_map)

    print("\n--- PATIENT OUTCOMES ---")
    n_total = len(final_states)
    print(f"Total patients: {n_total}")

    triages_in_data = sorted(final_states["triage"].dropna().unique())
    for triage in triages_in_data:
        subset = final_states[final_states["triage"] == triage]
        n_triage = len(subset)
        if n_triage == 0:
            continue
        n_dead = (subset["is_dead"] == True).sum()
        n_safe = (subset["is_safe"] == True).sum()
        n_in_progress = n_triage - n_dead - n_safe

        print(f"\n  {triage}: {n_triage} patients")
        print(f"    Deaths:      {n_dead:4d} ({100*n_dead/n_triage:5.1f}%)")
        print(f"    Safe:        {n_safe:4d} ({100*n_safe/n_triage:5.1f}%)")
        print(f"    In progress: {n_in_progress:4d} ({100*n_in_progress/n_triage:5.1f}%)")

    n_dead_total = (final_states["is_dead"] == True).sum()
    n_safe_total = (final_states["is_safe"] == True).sum()
    n_in_progress_total = n_total - n_dead_total - n_safe_total
    print(f"\n  TOTAL:")
    print(f"    Deaths:      {n_dead_total:4d} ({100*n_dead_total/n_total:5.1f}%)")
    print(f"    Safe:        {n_safe_total:4d} ({100*n_safe_total/n_total:5.1f}%)")
    print(f"    In progress: {n_in_progress_total:4d} ({100*n_in_progress_total/n_total:5.1f}%)")

    # -----------------------------------------------------------------
    # 2. Waiting time statistics
    # -----------------------------------------------------------------
    if not wait_times_df.empty:
        print("\n--- WAITING TIME STATISTICS (minutes) ---")
        print("Format: 25th percentile / Median / 75th percentile")

        facility_types = sorted(wait_times_df["facility_type"].unique())
        triages = sorted(wait_times_df["triage"].dropna().unique())

        for wait_type in ["care", "transport"]:
            print(f"\n  Waiting for {wait_type.upper()}:")
            wt_subset = wait_times_df[wait_times_df["wait_type"] == wait_type]

            if wt_subset.empty:
                print("    No data")
                continue

            for facility_type in facility_types:
                ft_subset = wt_subset[wt_subset["facility_type"] == facility_type]
                if ft_subset.empty:
                    continue

                print(f"\n    At {facility_type}:")
                for triage in triages:
                    t_subset = ft_subset[ft_subset["triage"] == triage]
                    if t_subset.empty:
                        continue

                    durations = t_subset["duration"].values
                    p25 = np.percentile(durations, 25)
                    p50 = np.percentile(durations, 50)
                    p75 = np.percentile(durations, 75)
                    print(f"      {triage}: {p25:6.1f} / {p50:6.1f} / {p75:6.1f}  (n={len(durations)})")

    # -----------------------------------------------------------------
    # 3. Cumulative transport time
    # -----------------------------------------------------------------
    if not transport_df.empty and distance_matrix is not None:
        print("\n--- CUMULATIVE TRANSPORT TIME ---")

        departures = transport_df[transport_df["event"] == "departure"].copy()
        arrivals = transport_df[transport_df["event"] == "arrival"].copy()

        amb_travel_times = {}
        for amb_id in transport_df["amb_id"].unique():
            amb_deps = departures[departures["amb_id"] == amb_id].sort_values("time")
            amb_arrs = arrivals[arrivals["amb_id"] == amb_id].sort_values("time")

            total_time = 0
            for _, arr in amb_arrs.iterrows():
                matching_deps = amb_deps[
                    (amb_deps["time"] < arr["time"]) &
                    (amb_deps["from_loc"] == arr["from_loc"]) &
                    (amb_deps["to_loc"] == arr["to_loc"])
                ]
                if not matching_deps.empty:
                    total_time += arr["time"] - matching_deps.iloc[-1]["time"]

            amb_travel_times[amb_id] = total_time

        total_transport_time = sum(amb_travel_times.values())
        print(f"  Total transport time (all ambulances): {total_transport_time:.1f} minutes")
        print("\n  By ambulance:")
        for amb_id, travel_time in sorted(amb_travel_times.items()):
            print(f"    {amb_id}: {travel_time:.1f} minutes")

    # -----------------------------------------------------------------
    # 4. Unit utilization
    # -----------------------------------------------------------------
    if unit_busy_periods and sim_duration > 0:
        print("\n--- UNIT UTILIZATION ---")

        for unit_id, periods in sorted(unit_busy_periods.items()):
            if not periods:
                print(f"  {unit_id}: 0.0%")
                continue

            total_busy = sum(p["end"] - p["start"] for p in periods)
            utilization = (total_busy / sim_duration) * 100
            print(f"  {unit_id}: {utilization:.1f}% ({total_busy:.1f} min busy / {sim_duration:.1f} min total)")

    print("\n" + "=" * 70)
