def load_data_from_xlsx(data_folder: str = "data/single_run/input", load_casualties: bool = True):
    """
    Load all simulation data from XLSX files in the specified folder.

    Expected structure:
        data_folder/
            components/
                distances/distance_matrix.xlsx
                AXPs/axp.xlsx
                facilities/facilities.xlsx
                units/units.xlsx
                ambulances/ambulances.xlsx
                c2/c2.xlsx
            policy_matrixes/
                facility_eligibility/facility_eligibility_0.xlsx (+ _1.xlsx, ...)
                ambulance_eligibility/ambulance_eligibility_0.xlsx (+ _1.xlsx, ...)
            casualty_dataframes/
                casualties.xlsx  (optional, generated by casualty_generator.py)

    Parameters:
        data_folder: path to data folder
        load_casualties: if True, load casualties.xlsx; if False, skip it

    Returns a dict with all DataFrames.
    """
    components_folder = os.path.join(data_folder, "components")
    policy_folder = os.path.join(data_folder, "policy_matrixes")

    # Distance matrix
    distance_matrix = pd.read_excel(os.path.join(components_folder, "distances", "distance_matrix.xlsx"), index_col=0)

    # AXP data - convert comma-separated string to list
    axp_df = pd.read_excel(os.path.join(components_folder, "AXPs", "axp.xlsx"))
    axp_df["assigned_facility_ids"] = axp_df["assigned_facility_ids"].apply(
        lambda x: [s.strip() for s in str(x).split(",")] if pd.notna(x) else []
    )

    # Facilities
    facility_df = pd.read_excel(os.path.join(components_folder, "facilities", "facilities.xlsx"))
    facility_df["c2_up_id"] = facility_df["c2_up_id"].replace({pd.NA: None, "": None}).where(
        facility_df["c2_up_id"].notna(), None
    )

    # Units — store raw params; distribution built inside Unit.setup() after env is seeded
    units_df = pd.read_excel(os.path.join(components_folder, "units", "units.xlsx"), dtype={"unit_id": str})
    units_df["service_time_params"] = units_df.apply(
        lambda r: {"type": "uniform", "low": float(r["service_time_min"]), "high": float(r["service_time_max"])}, axis=1
    )

    # Ambulances
    ambulance_df = pd.read_excel(os.path.join(components_folder, "ambulances", "ambulances.xlsx"))

    # Facility eligibility datasets — discover all _N.xlsx files, index by N
    fac_elig_folder = os.path.join(policy_folder, "facility_eligibility")
    fac_elig_datasets = {
        int(Path(f).stem.rsplit("_", 1)[-1]): pd.read_excel(os.path.join(fac_elig_folder, f), index_col=0)
        for f in sorted(os.listdir(fac_elig_folder)) if f.endswith(".xlsx") and not f.startswith("~$")
    }

    # Ambulance eligibility datasets
    amb_elig_folder = os.path.join(policy_folder, "ambulance_eligibility")
    amb_elig_datasets = {
        int(Path(f).stem.rsplit("_", 1)[-1]): pd.read_excel(os.path.join(amb_elig_folder, f), index_col=0)
        for f in sorted(os.listdir(amb_elig_folder)) if f.endswith(".xlsx") and not f.startswith("~$")
    }

    # C2 data - convert comma-separated strings to lists
    c2_df = pd.read_excel(os.path.join(components_folder, "c2", "c2.xlsx"))
    c2_df["facility_ids"] = c2_df["facility_ids"].apply(
        lambda x: [s.strip() for s in str(x).split(",")] if pd.notna(x) else []
    )
    c2_df["ambulance_ids"] = c2_df["ambulance_ids"].apply(
        lambda x: [s.strip() for s in str(x).split(",")] if pd.notna(x) else []
    )

    result = {
        "distance_matrix": distance_matrix,
        "axp_df": axp_df,
        "facility_df": facility_df,
        "units_df": units_df,
        "ambulance_df": ambulance_df,
        "c2_df": c2_df,
        "fac_eligibility_datasets": fac_elig_datasets,
        "amb_eligibility_datasets": amb_elig_datasets,
    }

    if load_casualties:
        # Casualties (generated by casualty_generator.py)
        # Raw lifetime parameter columns (lifetime_dist_type, lifetime_low,
        # lifetime_high, lifetime_mode) are passed directly to Patient.setup(),
        # which builds the salabim distribution inside the seeded environment.
        casualties_df = pd.read_excel(os.path.join(data_folder, "casualty_dataframes", "casualties.xlsx"))
        casualties_df["prescription"] = casualties_df["prescription"].apply(eval)
        result["casualties_df"] = casualties_df

    return result


